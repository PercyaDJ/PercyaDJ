#!/usr/bin/env bash
# Publishes the current state of the "now" frame to the `live` branch.
# The branch always holds a single commit, rewritten in place, so the main history stays clean.
# Usage: tools/update_live.sh [--force]
set -euo pipefail

hour=${NOW_HOUR:-$(TZ=Europe/Paris date +%-H)}  # NOW_HOUR: test override
if   [ "$hour" -ge 22 ]; then slot=22
elif [ "$hour" -ge 18 ]; then slot=18
elif [ "$hour" -ge 14 ]; then slot=14
elif [ "$hour" -ge 10 ]; then slot=10
elif [ "$hour" -ge 8 ];  then slot=8
else slot=0
fi
case "$slot" in
  8) now=0 ;; 10) now=1 ;; 14) now=2 ;; 18) now=3 ;; *) now=4 ;;
esac
stamp="$slot $(git rev-parse HEAD:assets/live-src)"

current=""
if git fetch --quiet --depth=1 origin live 2>/dev/null; then
  current=$(git show FETCH_HEAD:state.txt 2>/dev/null || true)
fi
if [ "${1:-}" != "--force" ] && [ "$current" = "$stamp" ]; then
  echo "Slot $slot already published, nothing to do."
  exit 0
fi

out=$(mktemp -d)
for lang in en fr; do
  for i in 0 1 2 3 4; do
    if [ "$i" -eq "$now" ]; then src="slice-$i-$lang-now.svg"; else src="slice-$i-$lang.svg"; fi
    cp "assets/live-src/$src" "$out/slice-$i-$lang.svg"
  done
  for theme in dark light; do
    cp "assets/live-src/nowline-$slot-$lang-$theme.svg" "$out/nowline-$lang-$theme.svg"
  done
done
echo "$stamp" > "$out/state.txt"
printf 'Generated by .github/workflows/now-frame.yml. Do not edit: this branch is rewritten several times a day.\n' > "$out/README.md"

wt=$(mktemp -d)
git worktree add --quiet --detach "$wt"
(
  cd "$wt"
  git checkout --quiet --orphan live-publish
  git rm -rf --quiet .
  cp "$out"/* .
  git add -A
  git -c user.name="github-actions[bot]" \
      -c user.email="41898282+github-actions[bot]@users.noreply.github.com" \
      commit --quiet -m "Now frame: slot $slot"
  git push --quiet --force origin HEAD:refs/heads/live
)
git worktree remove --force "$wt"
git branch -D --quiet live-publish 2>/dev/null || true
echo "Published slot $slot (frame on slice $now)."
